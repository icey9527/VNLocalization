.psp
; 文件0x54 = 内存0x8804000, 头差 = 0x8804000-0x54 = 0x8803FAC
; 之后 .org 直接写 IDA 内存地址
.open "rebuilt/PSP_GAME/SYSDIR/EBOOT.BIN", 0x8803FAC

; 全局: 所有"图标+文字"帮助条目(全游戏49处调用)的文字右移 GAP 像素, 图标不动
; 通用绘制函数 0x88E0B38 尾部两处文字落笔x, x累加寄存器是 s1
GAP equ 6 ;文字右移量, 想改就改这一个数
.org 0x88E0ED0 ;阴影文字 x: s1+1 -> s1+1+GAP
addiu a3, s1, 1+GAP
.org 0x88E0F04 ;主体文字 x: s1 -> s1+GAP
addiu a3, s1, GAP

; ===== 战利品消息语序修正(改程序版) =====
; loot_msg_build(0x8922A5C) 在 0x8922B58 调 sprintf类函数 sub_8813F28:
;   参数固定按序填%s: a2=来源串, a3=物品名, t0=动词串(该函数第5参走t0寄存器)
;   格式串 0x895F0F4 只能挪括号位置, 换不了参数顺序(已被实测证明)
; 改法: 对调 a3/t0 的取值, 变成 a3=动词, t0=物品
;   配合格式串 "%s%s【%s】"(BOOT.BIN偏移0x15B148, 已手动改好):
;   输出 = 来源 + 动词 + 【物品】 = "从宝箱中发现了「资金100」"
; 注意: 动词串(0x895F0CC見つけた/0x895F0DC落とした)翻译时不能带句尾标点
.org 0x8922B2C ;原 addiu a3,s4,zero (a3=物品名) -> t0=物品名
addu t0, s4, zero
.org 0x8922B54 ;原 lw t0,0(v0) (t0=动词串) -> a3=动词串
lw a3, 0(v0)
; 手改十六进制的话: 文件偏移0x11EB80 改 21 40 80 02 ; 0x11EBA8 改 00 00 47 8C

.close
