;==============================================================================
; ゆめりあ 汉化补丁 —— 让有语音的台词也显示文本
; 状态：2026-09-29 实机验证通过
;
; 【原版的问题】
;   有语音的台词不显示文本：
;     * 语音自然播完 → 直接跳到下一句（本句文本全程没出现）
;     * 按一下键打断语音 → 本句文本这才出来
;   等于看有语音的台词必须多按一下键，非常反人类。
;
; 【根因】（IDA 逆向 SLPS_252.35）
;   台词由场景命令 #181(sub_161940，角色台词) / #182(sub_161C08，旁白) 处理。
;   两个函数里都有一段一模一样的判断：
;
;       cfg = qword_277A80                        ; 配置区
;       v19 = (说话人号 < 10) ? cfg[5] : cfg[4]   ; +4/+5 = 「有语音」设定
;       if (v19)  v14 = 1                         ; 有语音 → 只排队播语音
;       else      v13 = 1                         ; 无语音 → v13 = 1 = 立即显示
;       ……
;       sub_16A068(&unk_274A38, 名字, 正文, p)     ; 设置正文（内部先把 +0xBF 置 1）
;       sub_16AF0C(&unk_274A38, v13)               ; ★ 再用 v13 覆盖 +0xBF
;
;   正文管理器 unk_274A38 的描画函数 sub_16A6E8 开头：
;       if (!*(u8*)(mgr + 0xBF)) return 0;        ; ★ 开关为 0 → 一个字都不画
;
;   所以有语音时 v13 = 0 → +0xBF = 0 → 描画函数直接 return。
;   「按一下才出字」就是按键分支里的 sub_16AF0C(mgr, 1) 把开关重新打开了。
;
; 【修法】
;   把「立即显示标志」v13($s7) 无条件置 1；语音标志 v14($fp) 原样保留，
;   语音照常播放。效果：有语音的台词一开始就显示文本、打字机照跑、
;   按一下键正常进下一句。总共只改 4 条指令。
;
; 【注意】
;   * armips 是【就地修改】——每次都要从 backup 还原原版 ELF 再汇编。
;     一键.bat 里 elf_string.py w 已经保证这一点（它总是从 backup 拷出来写）。
;   * 文件偏移 = VA - 0x100000 + 0x1000（.open 的 0xFF000 已经处理了换算）。
;==============================================================================
.ps2
.open "Yumeria/SLPS_252.35", 0xFF000

;------------------------------------------------------------------------------
; (1) 场景命令 #181 sub_161940（角色台词）
;     0x1619F0  bnez $s3, loc_161A00   →   nop
;
;     原逻辑：说话人号($s3) != 0 时跳过 0x1619F8 的 li $s7,1（不置立即显示）。
;     改后：   无条件落到 0x1619F8 `li $s7,1`，v13 恒为 1。
;     语音标志 v14($fp) 在 0x161A18~0x161A20 另行判断，不受这条影响。
;
;     原指令编码: 03 00 60 16
;------------------------------------------------------------------------------
.org 0x1619F0
    nop

;------------------------------------------------------------------------------
; (2) 场景命令 #182 sub_161C08（旁白台词）—— cfg[5] 分支
;     0x161D38  li $v0, 1   →   addiu $s7, $zero, 1
;
;     这条是 0x161D34 `beqz $v0, ...` 的延迟槽（延迟槽必然执行）。
;     原来：$v0 = 1，延迟槽 0x161D40 `sw $v0` 把 1 存进 v21（语音标志）。
;     改后：$s7 = 1（v3 = 立即显示）；$v0 保持 0x161D30 读到的 cfg[5]，
;           这条路径上 cfg[5] 本来就是 1，sw 存进去的还是 1 → v21 保住，语音照播。
;
;     原指令编码: 01 00 02 24
;------------------------------------------------------------------------------
.org 0x161D38
    addiu   $s7, $zero, 1

;------------------------------------------------------------------------------
; (3) 场景命令 #182 sub_161C08（旁白台词）—— cfg[4] 分支
;     0x161D4C  li $a0, 1   →   addiu $s7, $zero, 1
;
;     和 (2) 同理：v3 = 1。$a0 原来装的 1 是给下一条 sw 用的（见 (4)）。
;
;     原指令编码: 01 00 04 24
;------------------------------------------------------------------------------
.org 0x161D4C
    addiu   $s7, $zero, 1

;------------------------------------------------------------------------------
; (4) 配合 (3)：把 sw 的源寄存器从 $a0 换成 $v0
;     0x161D54  sw $a0, 0x10($sp)   →   sw $v0, 0x10($sp)
;
;     (3) 把 $a0 挪用了，这里改存 $v0 —— 它在 0x161D44 处刚读过 cfg[4]，
;     这条路径上 cfg[4] = 1，存下去 v21 仍是 1，语音标志保住。
;
;     原指令编码: 10 00 a4 af
;------------------------------------------------------------------------------
.org 0x161D54
    sw      $v0, 0x10($sp)

.close
